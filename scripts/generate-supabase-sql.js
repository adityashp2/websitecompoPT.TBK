const fs = require('fs');
const path = require('path');
const Database = require('better-sqlite3');

const dbPath = path.join(__dirname, '..', 'data', 'content.db');
let siteContentJson = '{}';
let adminUsers = [];

try {
  if (fs.existsSync(dbPath)) {
    const db = new Database(dbPath);
    const row = db.prepare("SELECT data FROM site_content WHERE id = 'main'").get();
    if (row && row.data) {
      siteContentJson = row.data;
    }
    adminUsers = db.prepare("SELECT username, email, password_hash, salt, name, role FROM admin_users").all();
  }
} catch (e) {
  console.error('Error reading sqlite:', e);
}

// Fallback admin if none found
if (!adminUsers || adminUsers.length === 0) {
  adminUsers = [{
    username: 'admin',
    email: 'admin@terbangbersamakawan.co.id',
    password_hash: '33e1b2baa4bcb70e19f400f9b4af8b6d64e98761ce67259c67a1715d773d5ae4b6725c348f780a3222a99ad21a88e30ecb9b242e16f70f8acd81ff76b2261b27',
    salt: '0f9ddce5bb354370cd92ff1c14eabcf2',
    name: 'Administrator PT. TBK',
    role: 'superadmin'
  }];
}

// Escape single quotes for SQL string literal
const escapedContentJson = siteContentJson.replace(/'/g, "''");
const admin = adminUsers[0];

const sql = `-- ========================================================
-- SKEMA DATABASE SUPABASE (POSTGRESQL)
-- Website Resmi PT. Terbang Bersama Kawan (PT. TBK)
-- ========================================================
-- Petunjuk:
-- 1. Buka dashboard Supabase Anda (https://supabase.com/dashboard)
-- 2. Pilih project Anda -> Masuk ke menu "SQL Editor"
-- 3. Tempel (Paste) seluruh isi script ini dan klik tombol "Run"
-- ========================================================

-- 1. TABEL KONTEN WEBSITE (CMS)
CREATE TABLE IF NOT EXISTS public.site_content (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABEL PESAN MASUK & FORMULIR MINAT KONSUMEN (INQUIRIES)
CREATE TABLE IF NOT EXISTS public.inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT,
  message TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABEL PENGGUNA ADMINISTRATOR
CREATE TABLE IF NOT EXISTS public.admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  email TEXT UNIQUE,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  name TEXT NOT NULL,
  role TEXT DEFAULT 'admin',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  last_login TIMESTAMP WITH TIME ZONE
);

-- 4. TABEL SESI LOGIN ADMINISTRATOR
CREATE TABLE IF NOT EXISTS public.admin_sessions (
  token TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.admin_users(id) ON DELETE CASCADE,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- INDEXES UNTUK PERFORMA QUERY CEPAT
CREATE INDEX IF NOT EXISTS idx_inquiries_created_at ON public.inquiries(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_admin_users_username ON public.admin_users(LOWER(username));
CREATE INDEX IF NOT EXISTS idx_admin_sessions_token ON public.admin_sessions(token);
CREATE INDEX IF NOT EXISTS idx_admin_sessions_expires_at ON public.admin_sessions(expires_at);

-- ========================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ========================================================
ALTER TABLE public.site_content ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_sessions ENABLE ROW LEVEL SECURITY;

-- Policy site_content: Siapapun dapat membaca data website (publik), simpan dibatasi
DROP POLICY IF EXISTS "Public can view site content" ON public.site_content;
CREATE POLICY "Public can view site content" 
  ON public.site_content FOR SELECT 
  USING (true);

DROP POLICY IF EXISTS "Service role has full access to site content" ON public.site_content;
CREATE POLICY "Service role has full access to site content" 
  ON public.site_content FOR ALL 
  USING (true) WITH CHECK (true);

-- Policy inquiries: Siapapun dapat mengirim formulir minat, baca/hapus oleh service role/admin
DROP POLICY IF EXISTS "Public can insert inquiries" ON public.inquiries;
CREATE POLICY "Public can insert inquiries" 
  ON public.inquiries FOR INSERT 
  WITH CHECK (true);

DROP POLICY IF EXISTS "Service role has full access to inquiries" ON public.inquiries;
CREATE POLICY "Service role has full access to inquiries" 
  ON public.inquiries FOR ALL 
  USING (true) WITH CHECK (true);

-- Policy admin: Akses via backend service role
DROP POLICY IF EXISTS "Service role has full access to admin_users" ON public.admin_users;
CREATE POLICY "Service role has full access to admin_users" 
  ON public.admin_users FOR ALL 
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service role has full access to admin_sessions" ON public.admin_sessions;
CREATE POLICY "Service role has full access to admin_sessions" 
  ON public.admin_sessions FOR ALL 
  USING (true) WITH CHECK (true);

-- ========================================================
-- SEED DATA AWAL (KONTEN RESMI & DEFAULT SUPERADMIN)
-- ========================================================

-- Seed Admin Default (username: admin, password: admin123)
INSERT INTO public.admin_users (username, email, password_hash, salt, name, role)
VALUES (
  '${admin.username}',
  '${admin.email}',
  '${admin.password_hash}',
  '${admin.salt}',
  '${admin.name}',
  '${admin.role}'
)
ON CONFLICT (username) DO NOTHING;

-- Seed Data Resmi Website PT. TBK
INSERT INTO public.site_content (id, data, updated_at)
VALUES (
  'main',
  '${escapedContentJson}'::jsonb,
  now()
)
ON CONFLICT (id) DO UPDATE 
SET data = EXCLUDED.data, updated_at = now();
`;

fs.writeFileSync(path.join(__dirname, '..', 'supabase_schema.sql'), sql, 'utf8');
const supabaseDir = path.join(__dirname, '..', 'supabase');
if (!fs.existsSync(supabaseDir)) {
  fs.mkdirSync(supabaseDir, { recursive: true });
}
fs.writeFileSync(path.join(supabaseDir, 'schema.sql'), sql, 'utf8');

console.log('Successfully generated supabase_schema.sql and supabase/schema.sql');
